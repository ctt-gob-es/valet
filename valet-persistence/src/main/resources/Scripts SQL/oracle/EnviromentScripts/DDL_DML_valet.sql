-- Tabla SIGNING_CERTIFICATE
CREATE TABLE "SIGNING_CERTIFICATE" (
    "ID_SIGNING_CERTIFICATE"		NUMBER(19) NOT NULL,
    "ISSUER" 						VARCHAR2(4000) NOT NULL,
  	"SUBJECT" 						VARCHAR2(4000) NOT NULL,
  	"SERIAL_NUMBER" 				VARCHAR(64) NOT NULL,
  	"DATE_EXPIRED" 					TIMESTAMP NOT NULL,
  	"KEYSTORE"						CLOB NOT NULL,
