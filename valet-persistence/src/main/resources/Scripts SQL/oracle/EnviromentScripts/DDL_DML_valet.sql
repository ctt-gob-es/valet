COMMENT ON TABLE "SIGNING_CERTIFICATE" IS 'Tabla que almacena un almacen p12 con un unico certificado.';
COMMENT ON COLUMN "SIGNING_CERTIFICATE"."ID_SIGNING_CERTIFICATE" IS 'Identificador del certificado firmante.';
COMMENT ON COLUMN "SIGNING_CERTIFICATE"."ISSUER" IS 'Emisor del certificado firmante.';
COMMENT ON COLUMN "SIGNING_CERTIFICATE"."SUBJECT" IS 'Asunto del certificado firmante.';
COMMENT ON COLUMN "SIGNING_CERTIFICATE"."SERIAL_NUMBER" IS 'Numero de serie del certificado firmante.';
COMMENT ON COLUMN "SIGNING_CERTIFICATE"."DATE_EXPIRED" IS 'Fecha de caducidad del certificado firmante.';
COMMENT ON COLUMN "SIGNING_CERTIFICATE"."KEYSTORE" IS 'Almacen del p12 en base64.';
COMMENT ON COLUMN "SIGNING_CERTIFICATE"."KEYSTORE_PASSWORD" IS 'Password del almacen del p12.';

